import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../Web/wwwroot/tile-edge-tags.js', import.meta.url), 'utf8');
const { SIDES, edgeTagsForRotation, sharedEdgeCompatibility, validateFloorConnections } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const asset = (connector = 'floor') => ({ id: connector, role: 'ground', edges: Object.fromEntries(SIDES.map(side => [side, [`join.${connector}`]])) });
const floor = asset(), wall = asset('wall'), manual = asset('manual'), overlay = asset('overlay');
const directional = asset();
directional.edges = { north: ['join.exterior'], east: ['join.wall'], south: ['join.floor'], west: ['join.manual'] };
assert.deepEqual(SIDES, ['north', 'east', 'south', 'west']);
assert.deepEqual(edgeTagsForRotation(directional, 1).east, ['join.exterior']);
assert.deepEqual(edgeTagsForRotation(directional, -1).west, ['join.exterior']);
assert.deepEqual(edgeTagsForRotation(directional, 4), directional.edges);
assert(sharedEdgeCompatibility(directional, 'south', floor).compatible);
assert(!sharedEdgeCompatibility(directional, 'north', floor).compatible);
assert(sharedEdgeCompatibility(directional, 'east', floor, { a: -1 }).compatible);
assert(!sharedEdgeCompatibility(manual, 'east', manual).compatible);
assert(sharedEdgeCompatibility(overlay, 'east', floor).ignored);
floor.edges.east.push('material.stone', 'portal.open');
assert(sharedEdgeCompatibility(floor, 'east', asset()).compatible, 'Descriptive tags do not alter compatibility');
assert.throws(() => edgeTagsForRotation({ id: 'legacy' }), /missing.*edge metadata/);
assert(sharedEdgeCompatibility(asset('road'), 'east', asset('road')).compatible, 'Custom connector names work without code changes');
assert(!sharedEdgeCompatibility(asset('road'), 'east', asset('lava')).compatible);
assert(sharedEdgeCompatibility(asset('road.paved'), 'east', asset('road.paved')).compatible);
assert.throws(() => edgeTagsForRotation(asset('road_paved')), /valid join/);
const duplicate = asset();
duplicate.edges.north.push('material.stone', 'material.stone');
assert.throws(() => edgeTagsForRotation(duplicate), /valid join/);
const malformed = asset('invalid..name');
assert.throws(() => edgeTagsForRotation(malformed), /valid join/);
const multiple = asset();
multiple.edges.north.push('join.road');
assert.throws(() => edgeTagsForRotation(multiple), /exactly one/);
assert.throws(() => sharedEdgeCompatibility(floor, 'up', wall), /Unknown.*side/);
const piece = (tile, x, y, angle = 0) => ({ asset: tile, px: x * 128, py: y * 128, angle });
assert.deepEqual(validateFloorConnections([piece(floor, 0, 0), piece(asset(), 1, 0)]), []);
const conflicts = validateFloorConnections([piece(floor, 0, 0), piece(wall, 1, 0), piece(wall, 4, 0)]);
assert.deepEqual(conflicts, [{ x: 0, y: 0, side: 'east', neighborX: 1, neighborY: 0, tags: floor.edges.east, neighborTags: wall.edges.west }]);
assert.deepEqual(validateFloorConnections([piece(floor, 0, 0), piece({ ...wall, role: 'wall' }, 0, 0), piece(asset(), 1, 0)]), [], 'Wall overlays must not replace floor cells');
assert.equal(validateFloorConnections([piece(manual, 0, 0), piece(manual, 0, 1)]).length, 1);
assert.deepEqual(validateFloorConnections([piece(overlay, 0, 0), piece(floor, 0, 1)]), []);
assert.throws(() => validateFloorConnections([piece({ id: 'missing', role: 'ground' }, 0, 0)]), /edge metadata/);
console.log('PASS tile edge rotations, opposite edges, connector rules, metadata errors and floor grid validation.');
