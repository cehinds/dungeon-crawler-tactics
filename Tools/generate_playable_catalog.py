"""Regenerate the readable content catalog from the two canonical JSON files."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
data = root / 'UnityPackage/Runtime/Data'
combat = json.loads((data / 'combat-content.json').read_text())
game = json.loads((data / 'game-content.json').read_text())
abilities = {ability['id']: ability for ability in combat['abilities']}
stats = {item['classId']: item for item in game['classStats']}
inventory = {item['itemId']: item['count'] for item in game['startingInventory']}
lines = ['# Playable content catalog', '',
         'Generated by `python3 Tools/generate_playable_catalog.py`. JSON is the authored source of truth. Numeric values are game adaptations.', '']

def table(title, headers, rows):
    lines.extend(['## ' + title, '', '| ' + ' | '.join(headers) + ' |',
                  '|' + '|'.join('---' for _ in headers) + '|'])
    lines.extend('| ' + ' | '.join(str(value) for value in row) + ' |' for row in rows)
    lines.append('')

table('Roster', ['Character', 'Default class', 'Field role', 'Personal actions'],
      [(r['label'], r['classId'], 'Deployable' if r.get('deployable', True) else 'Camp advisor',
        ', '.join(abilities[a]['label'] for a in r.get('innateAbilityIds', [])) or '—') for r in game['roster']])
table('Classes', ['ID', 'Class', 'HP / Mana / Move', 'Granted actions'],
      [(c['id'], c['label'], f"{stats[c['id']]['hp']} / {stats[c['id']]['energy']} / {stats[c['id']]['move']}",
        ', '.join(abilities[a]['label'] for a in c['abilityIds'])) for c in combat['classes']])
table('Abilities', ['ID', 'Label', 'Target / Range / Mana cost', 'Effects', 'Incoming tags'],
      [(a['id'], a['label'], f"{a['target']} / {a['range']} / {a['cost']}",
        '; '.join(f"{effect['op']} {effect.get('tag') or effect.get('amount', 0)}" for effect in a['effects']) or 'Reaction trigger',
        ', '.join(a['incomingTags']) or '—') for a in combat['abilities']])
table('Consumables', ['ID', 'Label', 'Ability', 'Initial supply'],
      [(i['id'], i['label'], i['abilityId'], inventory.get(i['id'], 0)) for i in combat['items']])
table('Encounters', ['Encounter', 'Enemies', 'XP'],
      [(e['label'], ', '.join(u['label'] for u in e['enemies']), e['xp']) for e in game['encounters']])
progression = game.get('progression', {})
table('Party levels', ['Level', 'Cumulative XP', 'HP bonus', 'Mana bonus'],
      [(level + 1, threshold, level * progression.get('hpPerLevel', 0), level * progression.get('manaPerLevel', 0))
       for level, threshold in enumerate(progression.get('xpThresholds', []))])
table('Personal skill unlocks', ['Crawler', 'Level', 'Skill'],
      [(skill['rosterId'], skill['level'], abilities[skill['abilityId']]['label']) for skill in progression.get('skillUnlocks', [])])
reward_win = {equipment_id: tier['requiredWins']
              for tier in game.get('equipmentRewardTiers', [])
              for equipment_id in tier['equipmentIds']}
table('Equipment', ['Item', 'Slot', 'Victories required', 'HP / Mana / Move bonus', 'Granted skills'],
      [(gear['label'], gear['slot'],
        f"Choose at win {reward_win[gear['id']]}" if gear.get('rewardOnly') and gear['id'] in reward_win else gear['unlockEncounter'],
        f"{gear['hpBonus']} / {gear['manaBonus']} / {gear['moveBonus']}",
        ', '.join(abilities[a]['label'] for a in gear['abilityIds']) or '—') for gear in game.get('equipment', [])])
lines.extend(['## Art and exploration', '',
              'Each encounter has an authored fog-covered exploration sector with optional caches, notes and a battle entrance. Discoveries persist in saves.', '',
              'The browser uses GPT-generated component atlases under `Web/wwwroot/assets/revamp/`, based on the selected art concept. `character-art.json` and `mongo-art.json` contain measured frame rectangles and foot anchors; frames are not assumed to be an exact uniform grid. Terrain, UI and effects have separate atlas metadata.', '',
              'All eight deployed character identities have four directional views with idle and two walking poses in `Web/wwwroot/assets/directional/manifest.json` (96 frames). Camera rotations select the correct view. The earlier textures remain Unity presenter fallbacks. The browser art is not yet integrated into Unity IMGUI.', ''])
(root / 'Docs/PlayableContent.md').write_text('\n'.join(lines))
print('Updated Docs/PlayableContent.md')
